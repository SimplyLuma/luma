# Runs only inside the disposable image build. No host/device disks are mounted.
set -euo pipefail
device=${LUMA_OS_DEVICE:-generic}
[ "$device" != generic ] || exit 0
src=/run/luma/source
inputs=/run/luma/hardware-inputs
[ "$(rpm --eval '%{_arch}')" = aarch64 ] || { echo 'Device kernel requires ARM64' >&2; exit 1; }
admission=$(python3 "$src/scripts/os/lib/hardware_inputs.py" --inputs "$inputs" --device "$device")
rpm_path=$(python3 -c 'import json,sys;print(json.load(sys.stdin)["kernel_rpm"])' <<<"$admission")
kver=$(python3 -c 'import json,sys;print(json.load(sys.stdin)["kernel_release"])' <<<"$admission")
# Hardware-specific userspace stays with the profile, beside its kernel/DTB.
# DNF records the selected Fedora versions in the normal image inventory.
package_selection=$(python3 - "$src/devices/$device/device.toml" <<'PYPACKAGES'
import pathlib,sys,tomllib
data=tomllib.loads(pathlib.Path(sys.argv[1]).read_text())
for request in data.get('userspace',{}).get('rpm_requires',[]):
    print(request)
PYPACKAGES
)
if [ -n "$package_selection" ]; then
  mapfile -t device_packages <<< "$package_selection"
  missing_packages=()
  for request in "${device_packages[@]}"; do
    installed=$(dnf5 --disablerepo='*' repoquery --installed --whatprovides "$request" --qf '%{name}')
    [ -n "$installed" ] || missing_packages+=("$request")
  done
  if [ "${#missing_packages[@]}" -gt 0 ]; then
    dnf5 -y --setopt=keepcache=False install "${missing_packages[@]}"
    dnf5 clean all >/dev/null
  fi
fi
mapfile -t old_kernels < <(find /usr/lib/modules -mindepth 1 -maxdepth 1 -type d -printf '%f\n')
# Resolve the complete replacement in one dependency-checked transaction.
. "$src/scripts/os/lib/device-kernel.sh"
luma_replace_device_kernel "$rpm_path"
# RPM queries capabilities by name, unlike DNF's dependency expressions.
# Require one provider and inspect its actual versioned capability separately.
[ "$(rpm -q --whatprovides kernel-uname-r --qf '%{NAME}')" = kernel-surface-pro12 ]
rpm -q --provides kernel-surface-pro12 | grep -Fx "kernel-uname-r = $kver"
for old in "${old_kernels[@]}"; do
  [ "$old" != "$kver" ] || continue
  # Old initramfs files generated by the base compose are not RPM-owned.
  # The sole provider was checked above. Refuse an RPM-owned old boot image
  # before cleaning base-compose leftovers that RPM does not own.
  if rpm -qf "/usr/lib/modules/$old/vmlinuz" >/dev/null 2>&1; then
    echo 'The old kernel boot image is still RPM-owned' >&2; exit 1
  fi
  rm -rf -- "/usr/lib/modules/$old"
done
# Install data with image ownership/modes, not the build account's ACLs.
python3 - "$inputs" <<'PYFILES'
import json,os,pathlib,shutil,sys
root=pathlib.Path(sys.argv[1]);os.umask(0o022)
for row in json.loads((root/'hardware-inputs.json').read_text())['files']:
    if row['path'].startswith('rootfs/'):
        dest=pathlib.Path('/')/row['path'].removeprefix('rootfs/')
        dest.parent.mkdir(parents=True,exist_ok=True)
        shutil.copyfile(root/row['path'],dest)
        dest.chmod(0o644)
PYFILES
install -D -m 0644 "$inputs/hardware-inputs.json" /usr/share/luma/device/hardware-inputs.json
install -D -m 0644 "$src/devices/$device/device.toml" /usr/share/luma/device/device.toml
install -D -m 0644 "$src/devices/$device/boot.toml" /usr/share/luma/device/boot.toml
cmp "/usr/lib/modules/$kver/devicetree" "/usr/lib/modules/$kver/dtb/qcom/x1p42100-microsoft-sp12in.dtb"
python3 "$src/scripts/install/atlas-iso/device-firmware-dracut.py" configure / "$inputs/hardware-inputs.json"
# The ordinary finalizer rebuilds the initramfs for this one kernel and
# refreshes rpm-ostree's base database after this transaction.
printf 'Installed device inputs for %s, kernel %s\n' "$device" "$kver"
# Atlas and bootc already consume this standard kernel-argument declaration.
python3 - "$src/devices/$device/boot.toml" <<'PYKARGS'
import json,pathlib,sys,tomllib
boot=tomllib.loads(pathlib.Path(sys.argv[1]).read_text())
path=pathlib.Path('/usr/lib/bootc/kargs.d/50-luma-device.toml')
path.parent.mkdir(parents=True,exist_ok=True)
path.write_text('match-architectures = ["aarch64"]\nkargs = '+json.dumps(boot['cmdline']['args'])+'\n')
PYKARGS
