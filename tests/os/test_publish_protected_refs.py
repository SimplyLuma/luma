"""Exercise the publisher's actual ref guards with a real collection repository."""
from pathlib import Path
import os
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[2]

class ProtectedRefsTests(unittest.TestCase):
    def test_summary_metadata_changes_but_all_foreign_refs_stay_protected(self):
        source = (ROOT / 'scripts/os/publish-channel.sh').read_text()
        snapshot = source[source.index('protected_refs=$('):source.index('head=$(luma_os_channel_head')]
        guard = source[source.index('while read -r other expected; do'):source.index('published=$(date')]
        with tempfile.TemporaryDirectory(prefix='luma-protected-refs-') as folder:
            work = Path(folder)
            repo = work / 'repo'
            tree = work / 'tree'
            tree.mkdir()
            def ostree(*args):
                return subprocess.check_output(['ostree', '--repo=' + str(repo), *args], text=True).strip()
            ostree('init', '--mode=archive', '--collection-id=org.projectluma.ProtectedRefsTest')
            (tree / 'content').write_text('first\n')
            first = ostree('commit', '--branch=luma/1/x86_64/nightly', '--tree=dir=' + str(tree))
            selected = 'luma/1/aarch64/nightly'
            for ref in (selected, 'luma/1/x86_64/beta', 'vendor/custom-ref'):
                ostree('refs', '--create=' + ref, first)
            ostree('summary', '--update')
            metadata_before = ostree('rev-parse', 'ostree-metadata')
            environment = {**os.environ, 'repo': str(repo), 'ref': selected}
            protected = subprocess.check_output(['bash', '-euc', snapshot + '\nprintf "%s" "$protected_refs"'], env=environment, text=True)
            self.assertEqual(set(line.split()[0] for line in protected.splitlines()),
                             {'luma/1/x86_64/nightly', 'luma/1/x86_64/beta', 'vendor/custom-ref'})
            (tree / 'content').write_text('second\n')
            second = ostree('commit', '--branch=' + selected, '--tree=dir=' + str(tree))
            ostree('summary', '--update')
            self.assertNotEqual(metadata_before, ostree('rev-parse', 'ostree-metadata'))
            environment['protected_refs'] = protected
            def validate():
                return subprocess.run(['bash', '-euc', 'luma_os_die() { echo "$*" >&2; exit 1; };\n' + guard],
                                      env=environment, capture_output=True, text=True)
            self.assertEqual(validate().returncode, 0, 'Autogenerated metadata must not block ARM publication')
            for foreign in ('luma/1/x86_64/nightly', 'luma/1/x86_64/beta', 'vendor/custom-ref'):
                with self.subTest(foreign=foreign):
                    ostree('refs', '--force', '--create=' + foreign, second)
                    result = validate()
                    self.assertNotEqual(result.returncode, 0)
                    self.assertIn('publication changed another architecture/channel ref', result.stderr)
                    ostree('refs', '--force', '--create=' + foreign, first)
            self.assertEqual(validate().returncode, 0)

if __name__ == '__main__':
    unittest.main()
